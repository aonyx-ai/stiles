//! The `Cargo.toml` of the bundle
//!
//! The bundle depends on what its crates depend on outside tsrs, merged into
//! one table. It declares no features. The features of tsrs serve its own
//! development, and a feature of a workspace member would turn on in every
//! `--all-features` run of whisker.

use std::collections::BTreeMap;
use std::collections::BTreeSet;

use anyhow::Context;
use anyhow::Result;
use anyhow::bail;
use anyhow::ensure;

use crate::Revision;
use crate::metadata::DefaultFeatures;
use crate::metadata::Dependency;
use crate::metadata::Optionality;
use crate::metadata::Package;
use crate::rewrite::CrateName;

/// Whether the bundle has a build script
#[derive(Copy, Clone, Eq, PartialEq, Debug)]
pub(crate) enum BuildScript {
    Present,
    Absent,
}

/// What the manifest describes
#[derive(Copy, Clone, Debug)]
pub(crate) struct Bundle<'a> {
    pub(crate) name: &'a CrateName,
    pub(crate) revision: &'a Revision,
    pub(crate) packages: &'a [Package],
    pub(crate) crates: &'a BTreeSet<CrateName>,
    pub(crate) build_script: BuildScript,
}

/// The table a dependency goes in, such as `[target.'cfg(unix)'.dependencies]`
#[derive(Clone, Eq, PartialEq, Ord, PartialOrd, Hash, Debug)]
struct Section {
    target: Option<String>,
    kind: Kind,
}

/// The kind of a dependency that a build of the library needs
#[derive(Copy, Clone, Eq, PartialEq, Ord, PartialOrd, Hash, Debug)]
enum Kind {
    Normal,
    Build,
}

/// One dependency of the bundle, merged from every crate that declares it
#[derive(Clone, Eq, PartialEq, Debug)]
struct Merged {
    req: String,
    default_features: DefaultFeatures,
    features: BTreeSet<String>,
}

/// Returns the text of the manifest
pub(crate) fn render(bundle: &Bundle<'_>) -> Result<String> {
    let Bundle {
        name,
        revision,
        packages,
        crates,
        build_script,
    } = *bundle;

    let edition = one_value(packages, "edition", |package| Some(package.edition()))
        .context("failed to choose the edition")?;
    let license =
        one_value(packages, "license", Package::license).context("failed to choose the license")?;
    let rust_version = one_value(packages, "rust-version", Package::rust_version)
        .context("failed to choose the rust-version")?;
    let sections = merge(packages, crates).context("failed to merge the dependencies")?;

    let mut lines = vec![
        format!("# Generated by tools/bundle-tsrs from tsrs commit {revision}. Do not edit:"),
        "# change the tool or the submodule, and run `mise run rakko -- bundle-tsrs`.".to_owned(),
        "# The bundle takes the version of the workspace, so it releases with whisker.".to_owned(),
        "[package]".to_owned(),
        format!("name = \"{name}\""),
        "version.workspace = true".to_owned(),
        format!("edition = \"{}\"", edition.unwrap_or("2024")),
    ];
    if let Some(rust_version) = rust_version {
        lines.push(format!("rust-version = \"{rust_version}\""));
    }
    if let Some(license) = license {
        lines.push(format!("license = \"{license}\""));
    }
    lines.extend([
        "description = \"The TypeScript checker of tsrs, repackaged as one crate\"".to_owned(),
        "repository = \"https://github.com/aonyx-ai/whisker.git\"".to_owned(),
        "readme = \"README.md\"".to_owned(),
    ]);
    lines.push(match build_script {
        BuildScript::Present => "build = \"build.rs\"".to_owned(),
        BuildScript::Absent => "build = false".to_owned(),
    });
    lines.extend(
        [
            "",
            "[lib]",
            "path = \"src/lib.rs\"",
            "test = false",
            "doctest = false",
            "# rustdoc names a page after each item, and some diagnostic constants of",
            "# tsrs have names longer than a file system allows in a file name.",
            "doc = false",
            "",
            "# The code is upstream's, so the bundle inherits none of whisker's lints.",
            "[lints]",
        ]
        .map(str::to_owned),
    );

    for (Section { target, kind }, dependencies) in sections {
        lines.push(String::new());
        let table = match kind {
            Kind::Normal => "dependencies",
            Kind::Build => "build-dependencies",
        };
        lines.push(match target {
            Some(target) => format!("[target.'{target}'.{table}]"),
            None => format!("[{table}]"),
        });
        for (name, merged) in dependencies {
            lines.push(format!("{name} = {}", render_dependency(&merged)));
        }
    }

    lines.push(String::new());
    Ok(lines.join("\n"))
}

/// Returns the one value that every package holds for `key`
fn one_value<'a>(
    packages: &'a [Package],
    key: &str,
    value: impl Fn(&'a Package) -> Option<&'a str>,
) -> Result<Option<&'a str>> {
    let values: BTreeSet<Option<&str>> = packages.iter().map(value).collect();
    let mut values = values.into_iter();
    let Some(first) = values.next() else {
        return Ok(None);
    };
    ensure!(
        values.next().is_none(),
        "the tsrs crates disagree on their {key}, and the bundle has one"
    );
    Ok(first)
}

fn merge(
    packages: &[Package],
    crates: &BTreeSet<CrateName>,
) -> Result<BTreeMap<Section, BTreeMap<String, Merged>>> {
    let mut sections: BTreeMap<Section, BTreeMap<String, Merged>> = BTreeMap::new();
    for package in packages {
        for dependency in package.dependencies() {
            let name = dependency.name();
            if crates.contains(&CrateName::new(name)) {
                continue;
            }
            let (section, merged) = convert(package, dependency)
                .with_context(|| format!("failed to read the dependency on {name}"))?;
            let table = sections.entry(section).or_default();
            let Some(existing) = table.get_mut(name) else {
                table.insert(name.to_owned(), merged);
                continue;
            };
            ensure!(
                existing.req == merged.req,
                "the tsrs crates require {name} at {} and at {}",
                existing.req,
                merged.req
            );
            if merged.default_features == DefaultFeatures::On {
                existing.default_features = DefaultFeatures::On;
            }
            existing.features.extend(merged.features);
        }
    }
    Ok(sections)
}

fn convert(package: &Package, dependency: &Dependency) -> Result<(Section, Merged)> {
    let crate_name = package.name();
    let name = dependency.name();
    if let Some(rename) = dependency.rename() {
        bail!("{crate_name} renames {name} to {rename}, which the bundle does not support");
    }
    match dependency.optional() {
        Optionality::Required => {}
        Optionality::Optional => {
            bail!("{crate_name} depends on {name} as an option, and the bundle has no features")
        }
    }
    let kind = match dependency.kind() {
        None => Kind::Normal,
        Some("build") => Kind::Build,
        Some(other) => bail!("{crate_name} has a dependency of the unknown kind {other}"),
    };
    let req = dependency.req();

    Ok((
        Section {
            target: dependency.target().map(str::to_owned),
            kind,
        },
        Merged {
            req: req.strip_prefix('^').unwrap_or(req).to_owned(),
            default_features: dependency.default_features(),
            features: dependency.features().iter().cloned().collect(),
        },
    ))
}

fn render_dependency(merged: &Merged) -> String {
    let Merged {
        req,
        default_features,
        features,
    } = merged;
    if *default_features == DefaultFeatures::On && features.is_empty() {
        return format!("\"{req}\"");
    }

    let mut fields = vec![format!("version = \"{req}\"")];
    if *default_features == DefaultFeatures::Off {
        fields.push("default-features = false".to_owned());
    }
    if !features.is_empty() {
        let list: Vec<String> = features
            .iter()
            .map(|feature| format!("\"{feature}\""))
            .collect();
        fields.push(format!("features = [{}]", list.join(", ")));
    }
    format!("{{ {} }}", fields.join(", "))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn render_dependency_with_defaults_and_no_features_is_a_bare_requirement() {
        let merged = Merged {
            req: "2".to_owned(),
            default_features: DefaultFeatures::On,
            features: BTreeSet::new(),
        };

        let text = render_dependency(&merged);

        assert_eq!(text, "\"2\"");
    }

    #[test]
    fn render_dependency_without_defaults_lists_its_features() {
        let merged = Merged {
            req: "0.17".to_owned(),
            default_features: DefaultFeatures::Off,
            features: ["inline-more".to_owned()].into(),
        };

        let text = render_dependency(&merged);

        assert_eq!(
            text,
            "{ version = \"0.17\", default-features = false, features = [\"inline-more\"] }"
        );
    }

    #[test]
    fn trait_auto_build_script() {
        fn assert_auto<T: Send + Sync + Unpin>() {}
        assert_auto::<BuildScript>();
    }

    #[test]
    fn trait_auto_bundle() {
        fn assert_auto<T: Send + Sync + Unpin>() {}
        assert_auto::<Bundle<'_>>();
    }

    #[test]
    fn trait_auto_kind() {
        fn assert_auto<T: Send + Sync + Unpin>() {}
        assert_auto::<Kind>();
    }

    #[test]
    fn trait_auto_merged() {
        fn assert_auto<T: Send + Sync + Unpin>() {}
        assert_auto::<Merged>();
    }

    #[test]
    fn trait_auto_section() {
        fn assert_auto<T: Send + Sync + Unpin>() {}
        assert_auto::<Section>();
    }
}
